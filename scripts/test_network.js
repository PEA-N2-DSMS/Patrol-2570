'use strict';
const assert = require('node:assert/strict');
const N = require('../network.js');
const A=[99,16], J=[99.001,16], B=[99.002,16], C=[99.001,16.001];
const routes=[{from:'root',to:'B',coordinates:[A,B]},{from:'root',to:'C',coordinates:[A,J,C]},{from:'root',to:'J',coordinates:[A,J]}];
const graph=N.build(routes,'root');
assert.equal(graph.edges.size,3,'Shared trunk must not be counted twice');
const root=N.selection(graph,'root'), branch=N.selection(graph,'J');
assert.deepEqual(root.devices.sort(),['B','C','J']);
assert.deepEqual(branch.devices.sort(),['B','C']);
assert.equal(N.selection(graph,'B').devices.length,0);
assert.ok(Math.abs(root.length-(N.meters(A,J)+N.meters(J,B)+N.meters(J,C)))<.01);
assert.ok(Math.abs(branch.length-(N.meters(J,B)+N.meters(J,C)))<.01);
assert.equal(N.selection(graph,'unknown'),null);
const duplicate=N.build([...routes,routes[0]],'root');
assert.equal(N.selection(duplicate,'root').length,root.length);
assert.equal(N.build([],'root'),null);
assert.equal(N.build([{from:'root',to:'bad',coordinates:[[NaN,16],B]}],'root'),null);
console.log('PASS: merged road trunk, split destination inside road segment, branch descendants, deduplicated meters, leaf, missing/malformed roads');
